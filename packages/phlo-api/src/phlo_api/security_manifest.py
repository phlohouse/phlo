@dataclass(frozen=True)
class OperationSpec:
    """Security classification for one externally reachable operation."""

    operation_name: str
    surface: str
    action: str
    resource_type: str
    public: bool = False
    resource_keys: tuple[str, ...] = ()
    resource_sources: tuple[tuple[str, str], ...] = ()
    methods: tuple[str, ...] = ()
    path: str | None = None
    endpoint: str | None = None


