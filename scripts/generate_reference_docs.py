def topology_docs(root: Path) -> tuple[dict[str, object], str]:
    """Project the existing typed service definitions, including package companions."""
    prepare_imports(root)
    from phlo.plugins._service_yaml import load_service_yaml
    from phlo.plugins.discovery._service_definition import ServiceDefinition
    from phlo.plugins.discovery._service_dependency_resolution import resolve_service_dependencies

    definitions = {}
    services = []
    for path in sorted((root / "packages").glob("*/src/*/*.yaml")):
        manifest = load_service_yaml(path)
        if "name" not in manifest or "compose" not in manifest:
            continue
        definition = ServiceDefinition.from_dict(manifest, path.parent)
        if definition.name in definitions:
            raise ValueError(f"Duplicate service identity: {definition.name}")
        definition.validate_port_defaults()
        definitions[definition.name] = definition
        services.append(
            {
                "name": definition.name,
                "source": path.relative_to(root).as_posix(),
                "package": path.parts[-4],
                "profile": definition.profile,
                "default": definition.default,
                "depends_on": sorted(definition.depends_on),
                "ports": [asdict(port) for port in definition.ports],
            }
        )
    for definition in definitions.values():
        missing = set(definition.depends_on) - definitions.keys()
        if missing:
            raise ValueError(f"{definition.name}: unknown service dependencies: {sorted(missing)}")
    resolve_service_dependencies(list(definitions.values()))
    services.sort(key=lambda item: item["name"])
    data: dict[str, object] = {"schema_version": 1, "services": services}
    lines = [
        "# Service topology reference",
        "",
        "> Generated from package service manifests by `scripts/generate_reference_docs.py`. Do not edit directly.",
        "",
        "`ServiceDefinition` is the typed authority. These are declared startup dependencies and published port defaults, not runtime calls or deployment overrides. See [ownership and validation](../architecture/service-topology.md#typed-authority-and-projections).",
        "",
        "| Service | Package manifest | Dependencies | Host default → container/protocol (override) | Profile | Default |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for service in services:
        ports = (
            "; ".join(
                f"{port['host_port']} → {port['container_port']}/{port['protocol']} ({port['env_var'] or 'literal'})"
                for port in service["ports"]
            )
            or "none"
        )
        dependencies = ", ".join(f"`{name}`" for name in service["depends_on"]) or "none"
        lines.append(
            f"| `{service['name']}` | [{service['package']}](../../{service['source']}) | {dependencies} | {ports} | {service['profile'] or 'none'} | {str(service['default']).lower()} |"
        )
    return data, "\n".join(lines) + "\n"


def compatibility_surface(
    root: Path, cli: Mapping[str, Any], http: Mapping[str, Any]
) -> dict[str, object]:
    """Project the ADR 0053 decision 2 surface of the blessed_core profile."""
    prepare_imports(root)
    import phlo
    from phlo.hooks import events
    from phlo.plugins.discovery import PLUGIN_FAMILIES

    manifest = json.loads((root / "registry/support/v1.json").read_text(encoding="utf-8"))
    packages = sorted(
        item.removeprefix("package:")
        for item in manifest["profiles"]["blessed_core"]["components"]
        if item.startswith("package:")
    )
    commands = [
        {
            "command": command["command"],
            "package": command["package"],
            "parameters": [
                {key: value for key, value in parameter.items() if key != "help"}
                for parameter in command["parameters"]
            ],
        }
        for command in cli["commands"]
        if command["package"] in packages
    ]
    routes = [
        f"{item['method']} {item['path']}"
        for item in http["endpoints"]
        if item["path"] == "/health" or item["path"].startswith("/api/v1/")
    ]
    groups = sorted(
        {family.entry_point_group for family in PLUGIN_FAMILIES.values()}
        | {"phlo.plugins.observatory", "phlo.project_templates"}
    )
    entry_points: dict[str, list[str]] = {group: [] for group in groups}
    for package in packages:
        for entry_point in distribution(package).entry_points:
            if entry_point.group in entry_points:
                entry_points[entry_point.group].append(
                    f"{package}: {entry_point.name} = {entry_point.value}"
                )
    event_types = sorted(
        name
        for name, value in vars(events).items()
        if isinstance(value, type)
        and issubclass(value, events.HookEvent)
        and value is not events.HookEvent
    )
    python_api = sorted(name for name in phlo.__all__ if not name.startswith("_"))
    schemas = manifest["release_set"]["schemas"]
    return {
        "schema_version": 1,
        "profile": "blessed_core",
        "packages": packages,
        "counts": {
            "cli_commands": len(commands),
            "http_routes": len(routes),
            "python_api_names": len(python_api),
            "entry_point_groups": len(groups),
            "entry_points": sum(map(len, entry_points.values())),
            "hook_event_types": len(event_types),
        },
        "cli": commands,
        "http": routes,
        "python_api": python_api,
        "entry_points": {group: sorted(items) for group, items in entry_points.items()},
        "hook_events": {
            "envelope_version": events.EVENT_VERSION,
            "types": event_types,
        },
        "schemas": {name: schemas[name]["version"] for name in ("configuration", "database")},
    }


def render_json(data: object) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def outputs(root: Path) -> dict[Path, str]:
    destination = root / "docs/reference"
    result = {}
    built = {}
    builders: tuple[tuple[str, Callable[[Path], tuple[dict[str, object], str]]], ...] = (
        ("cli", cli_docs),
        ("settings", settings_docs),
        ("http-api", http_docs),
        ("support-matrix", support_docs),
        ("service-topology", topology_docs),
    )
    for name, builder in builders:
        data, markdown = builder(root)
        built[name] = data
        result[destination / f"{name}.md"] = markdown
        result[destination / "generated" / f"{name}.json"] = render_json(data)
    result[destination / "generated" / "compatibility-surface.json"] = render_json(
        compatibility_surface(root, built["cli"], built["http-api"])
    )
    return result


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent, text=True)
    temporary = Path(name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as file:
            file.write(content)
            file.flush()
            os.fsync(file.fileno())
        temporary.replace(path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def write_outputs(rendered: Mapping[Path, str], *, check: bool) -> list[Path]:
    changed = [
        path
        for path, content in rendered.items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    if not check:
        for path in changed:
            atomic_write(path, rendered[path])
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Report stale generated files without writing them."
    )
    args = parser.parse_args(argv)
    try:
        changed = write_outputs(outputs(ROOT), check=args.check)
    except Exception as exc:
        parser.exit(1, f"reference generation failed: {exc}\n")
    if args.check and changed:
        paths = "\n".join(f"  {path.relative_to(ROOT)}" for path in changed)
        parser.exit(
            1,
            f"generated reference documentation is stale:\n{paths}\nRun: python scripts/generate_reference_docs.py\n",
        )
    print(
        f"Reference documentation {'updated' if changed else 'already current'}: {len(changed)} file(s)."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
