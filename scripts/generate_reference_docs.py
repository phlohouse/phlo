def legacy_replacements(endpoints: list[dict[str, Any]]) -> list[dict[str, object]]:
    """Return the replacement row for every deprecated route, checked against the API."""
    routes = {f"{item['method']} {item['path']}" for item in endpoints}
    deprecated = {f"{item['method']} {item['path']}" for item in endpoints if item["deprecated"]}
    legacy = {
        f"{item['method']} {item['path']}"
        for item in endpoints
        if item["path"].startswith("/api/observatory/")
    }
    if not deprecated == legacy == set(LEGACY_REPLACEMENTS):
        raise RuntimeError(
            "Every /api/observatory route must be deprecated and listed in LEGACY_REPLACEMENTS; "
            f"not deprecated {sorted(legacy - deprecated)}, "
            f"unlisted {sorted(deprecated - set(LEGACY_REPLACEMENTS))}, "
            f"stale {sorted(set(LEGACY_REPLACEMENTS) - deprecated)}"
        )
    rows = []
    for route, (replacements, note) in sorted(LEGACY_REPLACEMENTS.items(), key=_route_key):
        unknown = [item for item in replacements if item not in routes or item in deprecated]
        if unknown:
            raise RuntimeError(f"{route} names replacements that are not live v1 routes: {unknown}")
        rows.append({"route": route, "replacements": list(replacements), "note": note})
    return rows


def _route_key(item: tuple[str, object]) -> tuple[str, str]:
    method, path = item[0].split(" ", 1)
    return path, method


def http_docs(root: Path) -> tuple[dict[str, object], str]:
    prepare_imports(root)
    try:
        from phlo_api.main import app

        schema = app.openapi()
    except Exception as exc:
        raise RuntimeError(f"Cannot load FastAPI OpenAPI from phlo_api.main: {exc}") from exc
    endpoints = []
    for path, operations in sorted(schema["paths"].items()):
        for method in METHODS:
            if method in operations:
                operation = operations[method]
                endpoints.append(
                    {
                        "method": method.upper(),
                        "path": path,
                        "summary": operation.get("summary", ""),
                        "tags": sorted(operation.get("tags", [])),
                        "operation_id": operation.get("operationId"),
                        "deprecated": bool(operation.get("deprecated")),
                    }
                )
    endpoints.sort(key=lambda item: (item["path"], item["method"]))
    replacements = legacy_replacements(endpoints)
    data: dict[str, object] = {
        "schema_version": 1,
        "api": schema["info"],
        "endpoint_count": len(endpoints),
        "endpoints": endpoints,
        "legacy_replacements": replacements,
    }
    lines = [
        "# HTTP API reference",
        "",
        "> Generated by `scripts/generate_reference_docs.py`. Do not edit the endpoint inventory directly.",
        "",
        "## Contract",
        "",
        "The API reports version `0.1.0` in OpenAPI. Phase 1 introduces `/api/v1` alongside unchanged legacy paths. Treat the API as alpha because the support manifest marks the current release as alpha.",
        "",
        "`/health` is public. The security manifest classifies every other route as protected. `/api/v1` always requires identity and authorization; legacy authorization can be optional outside regulated and production modes. See [Authentication and access](auth-and-access.md) for configuration.",
        "",
        f"OpenAPI marks all {len(replacements)} `/api/observatory` routes as deprecated. [ADR 0053](../architecture/decisions/0053-what-1-0-promises.md) decision 3 removes them at the `1.0.0` release commit. [Legacy route replacements](#legacy-route-replacements) lists each one with its `/api/v1` replacement, or `None` for the routes that are removed without one.",
        "",
        f"## Endpoints ({len(endpoints)})",
        "",
        "| Method | Path | Summary | Tags |",
        "| --- | --- | --- | --- |",
    ]
    for item in endpoints:
        lines.append(
            f"| `{item['method']}` | `{item['path']}` | {cell(item['summary'])} | {', '.join(f'`{tag}`' for tag in item['tags']) or 'none'} |"
        )
    lines += [
        "",
        "## Legacy route replacements",
        "",
        "Each deprecated route and the `/api/v1` route that replaces it. A route whose replacement is `None` has no first-party caller and is removed at the `1.0.0` release commit without a replacement (ADR 0053 decision 3, maintainer decision of 2026-10-31); a `/api/v1` resource for that capability can be added later as an additive change. Unlike the legacy routes, most `/api/v1` resources require an explicit `env` query parameter.",
        "",
        "| Deprecated route | Replacement | Notes |",
        "| --- | --- | --- |",
    ]
    for row in replacements:
        replacement = "<br>".join(f"`{item}`" for item in row["replacements"]) or "None"
        note = cell(row["note"]) if row["note"] else ""
        lines.append(f"| `{row['route']}` | {replacement} | {note} |")
    return data, "\n".join(lines).rstrip() + "\n"


def support_docs(root: Path) -> tuple[dict[str, object], str]:
    manifest = json.loads((root / "registry/support/v1.json").read_text(encoding="utf-8"))
    gate_map = {item["name"]: item for item in manifest["gates"]["components"]}
    components = []
    for plural, singular in (
        ("packages", "package"),
        ("services", "service"),
        ("capabilities", "capability"),
    ):
        for item in manifest[plural]:
            name = f"{singular}:{item['name']}"
            gate = gate_map.get(name, {})
            components.append(
                {
                    "component": name,
                    "target_profile": item.get("scope", "not specified"),
                    "target_status": item.get("target_status", "not specified"),
                    "current_maturity": item.get(
                        "current_maturity", manifest["current_release"]["maturity"]
                    ),
                    "readiness": gate.get("status", "not gated"),
                    "applicable_gates": gate.get("applicable_gates", []),
                    "blockers": gate.get("blocked_by", []),
                }
            )
