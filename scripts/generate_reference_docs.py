def roots(root: Path) -> list[Path]:
    return [root / "src", *sorted((root / "packages").glob("*/src"))]


def prepare_imports(root: Path) -> None:
    for path in reversed(roots(root)):
        value = str(path)
        if value not in sys.path:
            sys.path.insert(0, value)


def safe(value: object) -> object:
    if value is None or isinstance(value, str | int | float | bool):
        return value
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, Mapping):
        return {
            str(key): safe(item)
            for key, item in sorted(value.items(), key=lambda pair: str(pair[0]))
        }
    if isinstance(value, set | frozenset):
        return sorted((safe(item) for item in value), key=repr)
    if isinstance(value, tuple | list):
        return [safe(item) for item in value]
    if callable(value):
        return f"<factory:{getattr(value, '__qualname__', type(value).__name__)}>"
    return repr(value)


def cell(value: object) -> str:
    if value is None:
        return "none"
    if value == "":
        return '""'
    text = (
        value if isinstance(value, str) else json.dumps(value, sort_keys=True, ensure_ascii=False)
    )
    return text.replace("|", "\\|").replace("\n", " ")


def cli_docs(root: Path) -> tuple[dict[str, object], str]:
    prepare_imports(root)
    try:
        from phlo.cli.commands.commands import describe_commands
        from phlo.cli.main import cli
    except Exception as exc:
        raise RuntimeError(f"Cannot load the CLI contract: {exc}") from exc
    commands = describe_commands(cli)
    concrete: dict[str, Any] = {}
    owners: dict[str, str] = {}
    # The editable root install records no top-level modules, so name it explicitly.
    distributions = {"phlo": ["phlo"], **packages_distributions()}

    def visit(command: Any, path: list[str], owner: str) -> None:
        """Record each command and the distribution whose module defines its callback."""
        module = getattr(command.callback, "__module__", "")
        owner = distributions.get(module.partition(".")[0], [owner])[0]
        concrete[" ".join(path)] = command
        owners[" ".join(path)] = owner
        for name, child in sorted(getattr(command, "commands", {}).items()):
            if not child.hidden:
                visit(child, [*path, name], owner)

    visit(cli, ["phlo"], "phlo")
    for command in commands:
        command["package"] = owners[command["command"]]
        for parameter, actual in zip(
            command["parameters"], concrete[command["command"]].params, strict=True
        ):
            parameter.update(default=safe(actual.default), envvar=safe(actual.envvar))
    commands.sort(key=lambda item: item["command"])
    data: dict[str, object] = {
        "schema_version": 1,
        "command_count": len(commands),
        "commands": commands,
    }
    lines = [
        "# CLI reference",
        "",
        "> Generated by `scripts/generate_reference_docs.py`. Do not edit this page directly.",
        "",
        f"This page lists all {len(commands)} installed command paths. The generator reads the Click contract without running a command.",
        "",
        "Run `python scripts/generate_reference_docs.py` to regenerate this page and `generated/cli.json`.",
        "",
    ]
    for command in commands:
        lines += [f"## `{command['command']}`", "", command["description"] or "No description.", ""]
        capabilities = command["capabilities"]
        lines += [
            "Capabilities: "
            + ", ".join(f"`{key}={str(value).lower()}`" for key, value in capabilities.items()),
            "",
        ]
        if not command["parameters"]:
            lines += ["Parameters: none.", ""]
            continue
        lines += [
            "| Name | Kind | Options | Type | Required | Default | Other |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for parameter in command["parameters"]:
            options = [*parameter.get("options", []), *parameter.get("secondary_options", [])]
            details = []
            if parameter.get("choices"):
                details.append("choices: " + ", ".join(map(str, parameter["choices"])))
            if parameter.get("multiple"):
                details.append("multiple")
            if parameter.get("is_flag"):
                details.append("flag")
            if parameter.get("nargs") != 1:
                details.append(f"nargs={parameter['nargs']}")
            if parameter.get("envvar"):
                details.append(f"env: {cell(parameter['envvar'])}")
            lines.append(
                f"| `{parameter['name']}` | {parameter['kind']} | "
                f"{' '.join(f'`{option}`' for option in options) or 'none'} | `{parameter['type']}` | "
                f"{str(parameter['required']).lower()} | `{cell(parameter['default'])}` | {'; '.join(details) or 'none'} |"
            )
        lines.append("")
    return data, "\n".join(lines).rstrip() + "\n"


def setting_candidates(root: Path) -> list[tuple[Path, str]]:
    found = []
    for source in roots(root):
        for path in sorted(source.rglob("*.py")):
            try:
                tree = ast.parse(path.read_text(encoding="utf-8"))
            except (OSError, SyntaxError):
                continue
            for node in tree.body:
                if isinstance(node, ast.ClassDef) and any(
                    isinstance(base, ast.Name)
                    and base.id
                    in {
                        "BaseConfig",
                        "BaseSettings",
                        "ProcessOverrides",
                        "ProjectRootProcessSettings",
                    }
                    for base in node.bases
                ):
                    found.append((path, node.name))
    return found


def module_details(root: Path, path: Path) -> tuple[str, str]:
    source = next(candidate for candidate in roots(root) if path.is_relative_to(candidate))
    module = ".".join(path.relative_to(source).with_suffix("").parts)
    project = (
        root / "pyproject.toml" if source == root / "src" else source.parent / "pyproject.toml"
    )
    with project.open("rb") as file:
        package = tomllib.load(file)["project"]["name"]
    return module, package


def setting_environment_names(model: Any, name: str, field: Any) -> list[str]:
    """Describe actual environment names, including aliases and case-insensitive keys."""
    from pydantic import AliasChoices, AliasPath

    alias = field.validation_alias or field.alias
    if isinstance(alias, AliasChoices):
        names = [item if isinstance(item, str) else str(item.path[0]) for item in alias.choices]
    elif isinstance(alias, AliasPath):
        names = [str(alias.path[0])]
    elif isinstance(alias, str):
        names = [alias]
    else:
        names = [str(model.model_config.get("env_prefix", "")) + name]
    return (
        names
        if model.model_config.get("case_sensitive", False)
        else [item.upper() for item in names]
    )


def settings_docs(root: Path) -> tuple[dict[str, object], str]:
    prepare_imports(root)
    models = []
    for path, class_name in setting_candidates(root):
        module_name, package = module_details(root, path)
        model: dict[str, Any] = {
            "package": package,
            "module": module_name,
            "class": class_name,
            "source": str(path.relative_to(root)),
        }
        try:
            cls = getattr(importlib.import_module(module_name), class_name)
            fields = []
            inherited_fields = {}
            for name, field in sorted(cls.model_fields.items()):
                if name not in vars(cls).get("__annotations__", {}):
                    owner = next(
                        base
                        for base in cls.__mro__[1:]
                        if name in vars(base).get("__annotations__", {})
                    )
                    inherited_fields[name] = f"{owner.__module__}.{owner.__name__}"
                    continue
                if field.default_factory in (list, dict, set, tuple):
                    default: object = safe(field.default_factory())
                elif field.default_factory is not None:
                    default = safe(field.default_factory)
                elif field.is_required():
                    default = "<required>"
                else:
                    default = safe(field.default)
                fields.append(
                    {
                        "name": name,
                        "alias": safe(field.validation_alias or field.alias or name),
                        "environment_names": setting_environment_names(cls, name, field),
                        "annotation": str(field.annotation).replace("typing.", ""),
                        "required": field.is_required(),
                        "default": default,
                        "description": field.description,
                    }
                )
            model.update(status="introspected", fields=fields, inherited_fields=inherited_fields)
        except Exception as exc:
            model.update(status="unavailable", fields=[], error=f"{type(exc).__name__}: {exc}")
        models.append(model)
    models.sort(key=lambda item: (item["package"], item["module"], item["class"]))
    field_count = sum(len(model["fields"]) for model in models)
    unavailable = sum(model["status"] != "introspected" for model in models)
    data: dict[str, object] = {
        "schema_version": 1,
        "model_count": len(models),
        "field_count": field_count,
        "unavailable_model_count": unavailable,
        "models": models,
    }
    lines = [
        "# Settings reference",
        "",
        "> Generated by `scripts/generate_reference_docs.py`. Do not edit this page directly.",
        "",
        f"This inventory contains {field_count} fields from {len(models)} Pydantic settings models. {unavailable} models could not be introspected.",
        "",
        "Defaults come from model metadata. The generator does not instantiate settings or read environment values. Passwords and keys shown here are public development defaults from source code, not deployed secret values; replace them outside local development.",
        "",
        "Process-only models do not load project dotenv files and are read fresh at their documented execution boundary. A `none` override default means absent, not an effective runtime default; the description gives YAML, explicit-argument and contextual fallbacks. JSON strings retain operation-specific decoding and error handling rather than eager global validation. See [process settings and environment-read classification](../contributing/process-settings.md) for ownership, internal hooks and compatibility lifetimes.",
        "",
    ]
    for model in models:
        lines += [
            f"## `{model['package']}`: `{model['class']}`",
            "",
            f"Source: `{model['source']}`",
            "",
        ]
        if model["status"] != "introspected":
            lines += [f"Introspection unavailable: `{cell(model['error'])}`", ""]
            continue
        if model["inherited_fields"]:
            lines += ["Inherited fields are documented once under their declaring model:", ""]
            lines += [
                f"- `{name}`: `{owner}`." for name, owner in model["inherited_fields"].items()
            ]
            lines.append("")
        if not model["fields"]:
            lines += ["This model declares no additional fields.", ""]
            continue
        lines += [
            "| Field | Environment names | Type | Required | Default | Description |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for field in model["fields"]:
            lines.append(
                f"| `{field['name']}` | `{cell(field['environment_names'])}` | `{cell(field['annotation'])}` | {str(field['required']).lower()} | `{cell(field['default'])}` | {cell(field['description'])} |"
            )
        lines.append("")
    return data, "\n".join(lines).rstrip() + "\n"


